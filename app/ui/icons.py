_cache = {}


def pixmap(name, color="#e6e9ec", size=24, dpr=1.0):
    key = (name, color, size, dpr)
    pm = _cache.get(key)
    if pm is not None:
        return pm
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
           f'<path fill="{color}" d="{PATHS.get(name, PATHS["info"])}"/></svg>')
    r = QSvgRenderer(QByteArray(svg.encode()))
    px = int(size * dpr)
    pm = QPixmap(px, px)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    r.render(p)
    p.end()
    pm.setDevicePixelRatio(dpr)
    _cache[key] = pm
    return pm


def icon(name, color="#e6e9ec", active="#30d5c8", size=24):
    ic = QIcon()
    for dpr in (1.0, 2.0):
        ic.addPixmap(pixmap(name, color, size, dpr), QIcon.Mode.Normal, QIcon.State.Off)
        ic.addPixmap(pixmap(name, active, size, dpr), QIcon.Mode.Normal, QIcon.State.On)
        ic.addPixmap(pixmap(name, active, size, dpr), QIcon.Mode.Active, QIcon.State.Off)
        ic.addPixmap(pixmap(name, "#5b636b", size, dpr), QIcon.Mode.Disabled, QIcon.State.Off)
    return ic
