export type StrKey = keyof typeof STRINGS;

let idx = 0;

export function setLang(lang: string): void {
  const l = lang || (navigator.language || 'en').slice(0, 2).toLowerCase();
  idx = l === 'tr' ? 0 : 1;
  document.documentElement.lang = idx === 0 ? 'tr' : 'en';
}

export function currentLang(): 'tr' | 'en' {
  return idx === 0 ? 'tr' : 'en';
}

export function t(key: StrKey, ...args: (string | number)[]): string {
  let s: string = STRINGS[key][idx];
  args.forEach((a, i) => { s = s.replace(`{${i}}`, String(a)); });
  return s;
}

/** Hesap bitiş tarihi: epoch saniye ya da portalın verdiği metin; sınırsızsa ''. */
export function expiryText(exp: string): string {
  const e = (exp || '').trim();
  if (!e || e === '0' || e === 'null' || e === '-') return '';
  if (/^\d+$/.test(e)) return new Date(parseInt(e, 10) * 1000).toLocaleDateString(currentLang() === 'tr' ? 'tr-TR' : 'en-GB');
  return e;
}
